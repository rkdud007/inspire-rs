#[derive(Parser, Debug)]
#[command(
    version,
    about = "Static keyword PIR server for ML-KEM-768 public keys"
)]
struct Args {
    /// Input dataset file generated by `gen_dataset`.
    #[arg(long)]
    dataset: PathBuf,

    /// Server listen address.
    #[arg(long, default_value = "0.0.0.0:8082")]
    listen: String,

    /// Number of cuckoo buckets / PIR items.
    #[arg(long)]
    buckets: Option<usize>,

    /// First-dimension size override.
    #[arg(long)]
    dim0: Option<usize>,
}

fn default_bucket_count(record_count: usize) -> usize {
    (record_count.max(512) * 2).next_power_of_two()
}

fn build_cuckoo_table(dataset: &Dataset, num_items: usize) -> CuckooTable {
    let params = CuckooParams::new(
        num_items,
        PUBLIC_KEY_ID_LEN,
        dataset.public_key_len,
        0,
        DETERMINISTIC_SEED,
    );
    let mut table = CuckooTable::new(params);

    for record in &dataset.records {
        table.insert(&record.public_key_id, &record.public_key);
    }

    table
}

fn process_keyword_query(
    stream: &mut TcpStream,
    table: &CuckooTable,
    params: &Params,
    pack_params: &PackParams,
    precomp_inspir_vec: &[PrecompInsPIR<'_>],
    db_rows: usize,
    db_cols: usize,
    gamma: usize,
    interpolate_degree: usize,
    c: usize,
    rlwe_q_prime_1: u64,
    rlwe_q_prime_2: u64,
) -> io::Result<()> {
    let (msg_type, query_bytes) = recv_msg(stream)?;
    if msg_type != MSG_KEYWORD_QUERY {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("unexpected message type: {msg_type}"),
        ));
    }

    let (packing_keys, per_query) = deserialize_keyword_query(params, pack_params, query_bytes);
    cuda_packing_online::gpu_expand_and_set_keys(
        packing_keys.y_body_condensed.as_ref().unwrap(),
        packing_keys.z_body_condensed.as_ref().unwrap(),
        params,
    );

    let rgsw_fold_and_switch = |ct_gsw_body: &PolyMatrixNTT<'_>,
                                packed: &[PolyMatrixRaw<'_>]|
     -> Vec<u8> {
        let mut ct_gsw = ct_gsw_body.pad_top(1);
        for i in 0..ct_gsw.cols {
            let a =
                PolyMatrixRaw::random_rng(params, 1, 1, &mut ChaCha20Rng::from_seed(RGSW_SEEDS[i]));
            ct_gsw.copy_into(&(-&a).ntt(), 0, i);
        }

        let ell = ct_gsw.cols / 2;
        let rgsw_results: Vec<PolyMatrixRaw<'_>> = (0..c)
            .into_par_iter()
            .map(|which_poly| {
                let mut ginv_c = PolyMatrixRaw::zero(params, 2 * ell, 1);
                let mut ginv_c_ntt = PolyMatrixNTT::zero(params, 2 * ell, 1);
                let mut sum = PolyMatrixRaw::zero(params, 2, 1);
                for i in (0..interpolate_degree).rev() {
                    let mut prod = PolyMatrixNTT::zero(params, 2, 1);
                    gadget_invert(&mut ginv_c, &sum);
                    to_ntt(&mut ginv_c_ntt, &ginv_c);
                    multiply(&mut prod, &ct_gsw, &ginv_c_ntt);
                    sum = &prod.raw() + &packed[which_poly * interpolate_degree + i];
                    sum.reduce_mod(params.modulus);
                }
                sum
            })
            .collect();

        rgsw_results
            .iter()
            .map(|ct| ct.switch_and_keep(rlwe_q_prime_1, rlwe_q_prime_2, gamma))
            .collect::<Vec<_>>()
            .concat()
    };

    let gpu_first_pass = |packed_query_row: &AlignedMemory64| -> Vec<PolyMatrixRaw<'_>> {
        let mut intermediate = AlignedMemory64::new(db_cols);
        cuda_gemv::gpu_gemv(
            intermediate.as_mut_slice(),
            packed_query_row.as_slice(),
            db_rows,
            db_cols,
            &params.moduli,
            &params.barrett_cr_1,
            params.mod0_inv_mod1,
            params.mod1_inv_mod0,
            params.modulus,
            params.barrett_cr_0_modulus,
            params.barrett_cr_1_modulus,
        );
        cuda_packing_online::gpu_packing_online_run(
            params,
            precomp_inspir_vec,
            intermediate.as_slice(),
            gamma,
        )
    };

    let mut all_responses = Vec::with_capacity(per_query.len());
    if per_query.len() == 2 {
        let packed_0 = gpu_first_pass(&per_query[0].0);
        let (response_0, packed_1) = rayon::join(
            || rgsw_fold_and_switch(&per_query[0].1, &packed_0),
            || gpu_first_pass(&per_query[1].0),
        );
        let response_1 = rgsw_fold_and_switch(&per_query[1].1, &packed_1);
        all_responses.push(response_0);
        all_responses.push(response_1);
    } else {
        for (packed_query_row, ct_gsw_body) in &per_query {
            let packed = gpu_first_pass(packed_query_row);
            let response = rgsw_fold_and_switch(ct_gsw_body, &packed);
            all_responses.push(response);
        }
    }

    let stash_entries = table.stash.clone();
    let empty_sidecar: [(Vec<u8>, Vec<u8>); 0] = [];
    let response_data =
        serialize_keyword_response(&all_responses, &stash_entries, &empty_sidecar, 0);
    send_msg(stream, MSG_KEYWORD_RESPONSE, &response_data)
}

fn log(msg: &str) {
    use std::time::{SystemTime, UNIX_EPOCH};
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    eprintln!("[init {:>6}s] {}", secs % 100000, msg);
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    env_logger::init();
    let args = Args::parse();

    log("loading dataset");
    let dataset = load_dataset(&args.dataset)?;
    if dataset.records.is_empty() {
        return Err("dataset must contain at least one record".into());
    }
    log(&format!(
        "loaded {} {} records (public key {} bytes)",
        dataset.records.len(),
        dataset.kem_name,
        dataset.public_key_len
    ));

    let num_items = args
        .buckets
        .unwrap_or_else(|| default_bucket_count(dataset.records.len()));
    if num_items < dataset.records.len() {
        return Err(format!(
            "bucket count {} must be >= record count {}",
            num_items,
            dataset.records.len()
        )
        .into());
    }

    let entry_size = PUBLIC_KEY_ID_LEN + dataset.public_key_len;
    let item_size_bits = entry_size * 8;
    if item_size_bits % 16 != 0 {
        return Err("entry size must be a multiple of 16 bits".into());
    }

    log("initializing CUDA memory pool");
    cuda_encode::init_memory_pool();
    log("CUDA memory pool ready");

    let dim0 = args.dim0.unwrap_or_else(|| {
        let default_dim0 = if num_items >= 256_000_000 {
            32768
        } else {
            2048
        };
        let (_params, _, (db_rows, _, _)) =
            params_rgswpir_given_input_size_and_dim0(num_items, item_size_bits, default_dim0);
        db_rows
    });
    log(&format!(
        "PIR params: buckets={} entry_size={} dim0={}",
        num_items, entry_size, dim0
    ));

    let params: &'static Params = Box::leak(Box::new({
        let (p, _, _) = params_rgswpir_given_input_size_and_dim0(num_items, item_size_bits, dim0);
        p
    }));
    let interpolate_degree = {
        let (_, id, _) = params_rgswpir_given_input_size_and_dim0(num_items, item_size_bits, dim0);
        id
    };

    let gamma = params.poly_len;
    let poly_len = params.poly_len;
    let db_rows = 1 << (params.db_dim_1 + params.poly_len_log2);
    let db_cols = params.instances * params.poly_len;
    let db_cols_prime = db_cols / gamma;
    let c = db_cols_prime / interpolate_degree;
    let pt_modulus = params.pt_modulus;
    if num_items < db_rows {
        // Find the minimum record count whose default bucket count meets db_rows.
        // default_bucket_count(n) = (n.max(512) * 2).next_power_of_two()
        // That equals db_rows when n > db_rows/2, so min_records = db_rows/2 + 1.
        let min_records = db_rows / 2 + 1;
        return Err(format!(
            "bucket count {} is too small for the PIR scheme (needs at least {}); \
             regenerate the dataset with at least {} records, or pass --buckets {}",
            num_items, db_rows, min_records, db_rows
        )
        .into());
    }
    let per = num_items / db_rows;
    let item_size_elements = item_size_bits / 16;
    log(&format!(
        "db layout: rows={} cols={} gamma={} interpolate_degree={} c={} per={}",
        db_rows, db_cols, gamma, interpolate_degree, c, per
    ));

    log("building cuckoo table");
    let table = build_cuckoo_table(&dataset, num_items);
    log("converting cuckoo table to raw DB");
    let raw_db = table.to_raw_db(db_rows, db_cols, per, item_size_elements);

    log("encoding database on GPU");
    let num_inv = invert_uint_mod(interpolate_degree as u64, pt_modulus).unwrap();
    let mut dummy_out = vec![0u16; raw_db.len().min(8)];
    let db_out_slice =
        unsafe { std::slice::from_raw_parts_mut(dummy_out.as_mut_ptr(), raw_db.len()) };
    cuda_encode::gpu_encode_database(
        &raw_db,
        db_out_slice,
        db_rows,
        db_cols,
        interpolate_degree,
        gamma,
        c,
        pt_modulus,
        num_inv,
    );
    drop(dummy_out);
    log("GPU database encoded");

    log("uploading database to GPU device memory");
    let d_db_ptr = cuda_encode::get_device_db();
    cuda_gemv::gpu_set_device_db(d_db_ptr, db_rows, db_cols);
    log("GPU device database set");

    let packing_params_new = PackParams::new(params, gamma);
    let half_packing_params = PackParams::new(params, gamma >> 1);
    let mut packing_params_set = HashMap::new();
    let mut half_packing_params_set = HashMap::new();
    packing_params_set.insert(gamma, packing_params_new);
    half_packing_params_set.insert(gamma, half_packing_params);

    let smaller_params = params.clone();
    let db_buf_aligned = AlignedMemory64::new(1);
    type T = u16;
    let y_server: &'static YServer<'static, T> = Box::leak(Box::new(YServer {
        params,
        packing_params_set,
        half_packing_params_set,
        smaller_params,
        db_buf_aligned,
        phantom: PhantomData,
        protocol_type: ProtocolType::SimplePIR,
        second_level_packing_mask: PackingType::InspiRING,
        second_level_packing_body: PackingType::NoPacking,
    }));

    log("running offline precomputation (SimplePIR) — this may take a while");
    let mut measurement = Measurement::default();
    let offline_vals =
        y_server.perform_offline_precomputation_simplepir(gamma, Some(&mut measurement), false);
    let precomp_inspir_vec = offline_vals.precomp_inspir_vec;
    log("offline precomputation done");

    if !cuda_packing_online::is_rotation_tables_uploaded() {
        log("uploading GPU rotation tables");
        cuda_packing_online::gpu_rotation_setup_tables(
            &y_server.packing_params_set[&gamma],
            params,
        );
        log("rotation tables uploaded");
    }

    let pack_params = PackParams::new_fast(params, gamma);
    let rlwe_q_prime_1 = params.get_q_prime_1();
    let rlwe_q_prime_2 = params.get_q_prime_2();

    let handshake = HandshakeParams {
        num_items,
        item_size_bits,
        dim0,
        keyword_pir: Some(KeywordPirHandshake {
            cuckoo_seed: DETERMINISTIC_SEED.to_vec(),
            num_hashes: 2,
            key_size: PUBLIC_KEY_ID_LEN,
            value_size: dataset.public_key_len,
            entry_size,
            num_accounts: dataset.records.len(),
            kem_name: dataset.kem_name.clone(),
        }),
    };
    let handshake_json = serde_json::to_vec(&handshake)?;

    println!(
        "serving {} {} public keys on {}",
        dataset.records.len(),
        dataset.kem_name,
        args.listen
    );
    println!(
        "entry size {} bytes, buckets {}, dim0 {}",
        entry_size, num_items, dim0
    );

    let listener = TcpListener::bind(&args.listen)?;
    for incoming in listener.incoming() {
        let mut stream = match incoming {
            Ok(stream) => stream,
            Err(err) => {
                eprintln!("accept error: {err}");
                continue;
            }
        };
        stream.set_nodelay(true).ok();

        if let Err(err) = send_msg(&mut stream, MSG_HANDSHAKE, &handshake_json) {
            eprintln!("handshake send failed: {err}");
            continue;
        }

        loop {
            let start = Instant::now();
            match process_keyword_query(
                &mut stream,
                &table,
                params,
                &pack_params,
                &precomp_inspir_vec,
                db_rows,
                db_cols,
                gamma,
                interpolate_degree,
                c,
                rlwe_q_prime_1,
                rlwe_q_prime_2,
            ) {
                Ok(()) => {
                    println!(
                        "query answered in {:.1}ms",
                        start.elapsed().as_secs_f64() * 1000.0
                    );
                }
                Err(err) if err.kind() == io::ErrorKind::UnexpectedEof => break,
                Err(err) => {
                    eprintln!("client error: {err}");
                    break;
                }
            }
        }
    }

    Ok(())
}
